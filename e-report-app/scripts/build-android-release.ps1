function New-AndroidPassword {
  return (([guid]::NewGuid().ToString('N')) + ([guid]::NewGuid().ToString('N'))).Substring(0, 32)
}

function Read-EnvFile([string]$path) {
  $values = @{}
  if (-not (Test-Path -LiteralPath $path)) {
    return $values
  }
  Get-Content -LiteralPath $path -Encoding UTF8 | ForEach-Object {
    if ($_ -match '^\s*([^#=\s]+)=(.*)$') {
      $values[$matches[1]] = $matches[2].Trim().Trim('"').Trim("'")
    }
  }
  return $values
}

function Resolve-ExistingDirectory([string[]]$candidates, [string]$label) {
  foreach ($candidate in $candidates) {
    if ($candidate -and (Test-Path -LiteralPath $candidate -PathType Container)) {
      return (Resolve-Path -LiteralPath $candidate).Path
    }
  }
  throw "$label does not exist. Checked: $($candidates -join ', ')"
}

function Convert-ToGradlePath([string]$path) {
  return $path -replace '\\', '/'
}

function Merge-GradleJvmArgs([string]$line) {
  $currentArgs = if ($line -match '^org\.gradle\.jvmargs=(.*)$') { $matches[1].Trim() } else { '' }
  if (-not $currentArgs) {
    $currentArgs = '-Xmx3072m -XX:MaxMetaspaceSize=1024m'
  }
  if ($currentArgs -notmatch [regex]::Escape($requiredGradleJvmArg)) {
    $currentArgs = "$currentArgs $requiredGradleJvmArg"
  }
  return "org.gradle.jvmargs=$currentArgs"
}

function Resolve-AndroidSdkRoot {
  return Resolve-ExistingDirectory @(
    $env:ANDROID_HOME,
    $env:ANDROID_SDK_ROOT,
    $defaultAndroidSdkRoot
  ) 'Android SDK root'
}

function Resolve-GradleJavaHome {
  return Resolve-ExistingDirectory @(
    $env:E_REPORT_ANDROID_GRADLE_JAVA_HOME,
    $defaultGradleJavaHome,
    'D:\DevlopEnv\JDK\jdk-24.0.1',
    'D:\DevlopEnv\JDK\jdk-25',
    $env:JAVA_HOME
  ) 'Android Gradle Java home'
}

function Resolve-JavaToolchainPaths([string]$gradleJavaHome) {
  $candidates = @(
    'D:\DevlopEnv\Caches\gradle\jdks\eclipse_adoptium-17-amd64-windows.2',
    $gradleJavaHome,
    'D:\DevlopEnv\JDK\jdk-25',
    'D:\DevlopEnv\JDK\jdk-24.0.1',
    'D:\DevlopEnv\JDK\jdk-21.0.4'
  )
  $paths = New-Object System.Collections.Generic.List[string]
  foreach ($candidate in $candidates) {
    if ($candidate -and (Test-Path -LiteralPath $candidate -PathType Container)) {
      $resolved = (Resolve-Path -LiteralPath $candidate).Path
      if (-not $paths.Contains($resolved)) {
        $paths.Add($resolved)
      }
    }
  }
  return $paths.ToArray()
}

function Resolve-GradleUserHome {
  $gradleUserHome = if ($env:E_REPORT_GRADLE_USER_HOME) {
    $env:E_REPORT_GRADLE_USER_HOME
  } else {
    $defaultGradleUserHome
  }
  New-Item -ItemType Directory -Force -Path $gradleUserHome | Out-Null
  return (Resolve-Path -LiteralPath $gradleUserHome).Path
}

function Write-AndroidLocalProperties([string]$sdkRoot) {
  $localProperties = Join-Path $appRoot 'android\local.properties'
  $content = @(
    "# Generated by scripts/build-android-release.ps1",
    "sdk.dir=$(Convert-ToGradlePath $sdkRoot)"
  )
  Set-Content -LiteralPath $localProperties -Encoding UTF8 -Value $content
}

function Write-GradleJavaHome([string]$javaHome, [string[]]$javaToolchainPaths) {
  $gradleProperties = Join-Path $env:GRADLE_USER_HOME 'gradle.properties'
  $escapedJavaHome = Convert-ToGradlePath $javaHome
  $escapedToolchainPaths = ($javaToolchainPaths | ForEach-Object { Convert-ToGradlePath $_ }) -join ','
  $lines = if (Test-Path -LiteralPath $gradleProperties) {
    Get-Content -LiteralPath $gradleProperties -Encoding UTF8
  } else {
    @()
  }
  $nextLines = @()
  $javaHomeUpdated = $false
  $jvmArgsUpdated = $false
  $toolchainPathsUpdated = $false
  $toolchainAutoDownloadUpdated = $false
  foreach ($line in $lines) {
    if ($line -match '^org\.gradle\.java\.home=') {
      $nextLines += "org.gradle.java.home=$escapedJavaHome"
      $javaHomeUpdated = $true
    } elseif ($line -match '^org\.gradle\.jvmargs=') {
      $nextLines += Merge-GradleJvmArgs $line
      $jvmArgsUpdated = $true
    } elseif ($line -match '^org\.gradle\.java\.installations\.paths=') {
      $nextLines += "org.gradle.java.installations.paths=$escapedToolchainPaths"
      $toolchainPathsUpdated = $true
    } elseif ($line -match '^org\.gradle\.java\.installations\.auto-download=') {
      $nextLines += "org.gradle.java.installations.auto-download=false"
      $toolchainAutoDownloadUpdated = $true
    } else {
      $nextLines += $line
    }
  }
  if (-not $jvmArgsUpdated) {
    $nextLines += Merge-GradleJvmArgs ''
  }
  if (-not $javaHomeUpdated) {
    $nextLines += "org.gradle.java.home=$escapedJavaHome"
  }
  if (-not $toolchainPathsUpdated) {
    $nextLines += "org.gradle.java.installations.paths=$escapedToolchainPaths"
  }
  if (-not $toolchainAutoDownloadUpdated) {
    $nextLines += "org.gradle.java.installations.auto-download=false"
  }
  Set-Content -LiteralPath $gradleProperties -Encoding UTF8 -Value $nextLines
}

function Write-SigningEnv([string]$storePassword, [string]$keyPassword) {
  $content = @(
    "E_REPORT_UPLOAD_STORE_FILE=$keystoreFile",
    "E_REPORT_UPLOAD_STORE_PASSWORD=$storePassword",
    "E_REPORT_UPLOAD_KEY_ALIAS=$keyAlias",
    "E_REPORT_UPLOAD_KEY_PASSWORD=$keyPassword"
  )
  Set-Content -LiteralPath $signingEnvFile -Encoding UTF8 -Value $content
}

function Ensure-SigningKey([string]$javaHome) {
  New-Item -ItemType Directory -Force -Path $privateDir | Out-Null
  $values = Read-EnvFile $signingEnvFile
  if ((Test-Path -LiteralPath $keystoreFile) -and $values.ContainsKey('E_REPORT_UPLOAD_STORE_PASSWORD') -and $values.ContainsKey('E_REPORT_UPLOAD_KEY_PASSWORD')) {
    if ($values['E_REPORT_UPLOAD_KEY_PASSWORD'] -ne $values['E_REPORT_UPLOAD_STORE_PASSWORD']) {
      Write-SigningEnv $values['E_REPORT_UPLOAD_STORE_PASSWORD'] $values['E_REPORT_UPLOAD_STORE_PASSWORD']
      $values = Read-EnvFile $signingEnvFile
    }
    return $values
  }

  $storePassword = New-AndroidPassword
  $keyPassword = $storePassword
  $keytoolCommand = Get-Command keytool.exe -ErrorAction SilentlyContinue
  if (-not $keytoolCommand) {
    $candidate = Join-Path $javaHome 'bin\keytool.exe'
    if (Test-Path -LiteralPath $candidate) {
      $keytoolCommand = Get-Item -LiteralPath $candidate
    }
  }
  if (-not $keytoolCommand) {
    throw 'keytool.exe not found. Install JDK or set PATH before building Android release.'
  }

  if (Test-Path -LiteralPath $keystoreFile) {
    Remove-Item -LiteralPath $keystoreFile -Force
  }
  & $keytoolCommand.Source `
    -genkeypair `
    -v `
    -storetype PKCS12 `
    -keystore $keystoreFile `
    -alias $keyAlias `
    -keyalg RSA `
    -keysize 2048 `
    -validity 10000 `
    -storepass $storePassword `
    -keypass $keyPassword `
    -dname 'CN=MNNU E-Report,O=MNNU,L=Nanjing,ST=Jiangsu,C=CN' | Out-Null

  Write-SigningEnv $storePassword $keyPassword
  return Read-EnvFile $signingEnvFile
}

